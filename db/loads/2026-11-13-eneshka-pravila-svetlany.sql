-- Правила заказов Енешки по ответам Светланы (13.11.2026, вторая анкета). Вносится только бесспорное:
-- то, что она назвала однозначно. Не вносится и остаётся вопросом: выходные дни (какие именно), цена платной
-- доставки, реквизиты Kaspi для предоплаты, «удалёнка» в способах оплаты, срок готовности свежих пирогов
-- («рассматриваем по загрузке» - бот больше не обещает срок сам, это правка bot/src/menu.ts).
-- Повторный прогон ничего не меняет сверх этого. Выполнять одной транзакцией (DO-блок с http_get и сверкой md5).

do $$
declare v_faq text;
begin
  -- 1. Минимум заказа на доставку: было 7 000, Светлана - «бесплатно от 10 000».
  update tandem.settings set value = '10000' where key = 'client_min_order';

  -- 2. Куда возим. Платные районы названы, цены нет - сумму говорит продавец.
  update tandem.settings set value = 'по Темиртау бесплатная; в Караганду, старый город, на правый берег и в отдалённые районы - платная, сумму назовёт продавец'
   where key = 'client_delivery_text';

  -- 3. Оплата при получении: переводов нет. «Удалёнка» из ответа не расшифрована - в правила не идёт.
  update tandem.settings set value = 'наличные (своему водителю), Kaspi QR' where key = 'client_payment_methods';

  -- 4. Предоплата всегда от 20 000. Правило читает tandem.order_quote (0050): from_sum:<сумма>.
  --    Реквизитов Kaspi пока нет - шаблон предоплаты пропускает строку с ними (tests/templates.test.ts).
  update tandem.settings set value = 'from_sum:20000' where key = 'client_prepay_rule';

  -- 5. Срок вперёд: «на практике брали и за месяц, и за 1,5» - ставим 45 дней вместо 14.
  update tandem.settings set value = '45' where key = 'client_max_days_ahead';

  -- 6. Частые вопросы: к прежнему тексту (о Енешке, халяль, аллергены) - ответы Светланы 13.11.2026.
  --    Пишем целиком, чтобы повторный прогон не удваивал абзацы.
  v_faq := 'О Енешке: домашняя кухня, ручная лепка полуфабрикатов, всегда свежая выпечка из качественных ингредиентов. Тесто отрабатывали специально, чтобы оно таяло во рту.
Особая позиция: пирог «Грибное лукошко» - начинки в нём больше, чем теста.
Мясо: только халяль, со свининой не работаем.
Аллергены: в составе есть яйца, орехи, молочные продукты. Позиций для аллергиков (без глютена и подобного) пока нет.
Где мы: Темиртау, улица Караганды, строение 1 (бывший «Бидай нан»). Парковка есть.
Магазин работает до 19:00.
Хранение: полуфабрикаты 3 месяца в морозильнике. Пироги замороженные 3 месяца, без заморозки 2 суток.
Отмена и изменение заказа: выпечку - не позже чем за сутки, полуфабрикаты - за час. Предоплату возвращаем.
Обеды в офис и на предприятие: возим, документы с НДС выставляем.
Самовывоз только из Енешки. В «Аяне» продаются полуфабрикаты, заказ туда оформить нельзя.
Если заказ не понравился: извиниться и позвать продавца, разбирается он.';
  update tandem.settings set value = v_faq where key = 'client_faq';

  -- Проверки: иначе откат всего.
  if (select value from tandem.settings where key = 'client_min_order') <> '10000'
     or (select value from tandem.settings where key = 'client_prepay_rule') <> 'from_sum:20000'
     or (select value from tandem.settings where key = 'client_max_days_ahead') <> '45'
     or (select value from tandem.settings where key = 'client_payment_methods') like '%перевод%'
     or (select length(value) from tandem.settings where key = 'client_faq') < 900
     or (select value from tandem.settings where key = 'client_faq') not like '%строение 1%'
  then raise exception 'Правила Светланы не записались';
  end if;
  -- Длина client_faq ограничена проверкой office_clients (0052): не больше 6000.
  if (select length(value) from tandem.settings where key = 'client_faq') > 6000 then
    raise exception 'client_faq длиннее 6000 - бэк-офис такой текст не примет';
  end if;
end $$;
